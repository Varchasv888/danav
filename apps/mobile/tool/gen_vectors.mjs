// Generates the fixtures the Flutter tests compare against: random invoices worked out by the server's own tax code (packages/domain),
// so the app's local arithmetic is proved to give the same paise. Run: node tool/gen_vectors.mjs
import { writeFileSync } from "node:fs";
import { computeInvoiceTax, lineGstRate, GST_RATES, GST_STATES, formatIndian, amountInWords } from "../../../packages/domain/dist/index.js";

let seed = 20261111;
const rnd = () => { seed = (seed * 1664525 + 1013904223) % 4294967296; return seed / 4294967296; };
const pick = (a) => a[Math.floor(rnd() * a.length)];
const dp = (n, d) => (Math.floor(rnd() * 10 ** (n)) / 10 ** d).toFixed(d);

const supplierStates = ["27", "29", "04", "07", "26", "18", "38"];
const cases = [];
while (cases.length < 1500) {
  const n = 1 + Math.floor(rnd() * 8);
  const lines = Array.from({ length: n }, () => {
    const qty = rnd() < 0.5 ? String(1 + Math.floor(rnd() * 200)) : (0.0001 + rnd() * 500).toFixed(pick([1, 2, 3, 4]));
    const rate = rnd() < 0.5 ? String(1 + Math.floor(rnd() * 20000)) : (0.01 + rnd() * 90000).toFixed(pick([2, 3, 4]));
    const gross = Number(qty) * Number(rate);
    const discount = rnd() < 0.4 ? (gross * rnd() * 0.5).toFixed(2) : "0";
    return { qty, rate, discount, gstRate: pick(GST_RATES), cessRate: rnd() < 0.15 ? pick(["1", "2.5", "12"]) : "0" };
  });
  const supplierState = pick(supplierStates);
  const place = rnd() < 0.5 ? supplierState : rnd() < 0.15 ? "96" : pick(["27", "29", "07", "33", "18"]);
  const ctx = { supplierState, placeOfSupply: place, sez: rnd() < 0.08, lut: rnd() < 0.2, reverseCharge: rnd() < 0.05, roundOff: rnd() < 0.9 };
  try { cases.push({ lines, ctx, expected: computeInvoiceTax(lines, ctx) }); } catch { /* a discount larger than the line: skipped */ }
}
writeFileSync("test/fixtures/tax_vectors.json", JSON.stringify(cases));

const amounts = ["0", "1", "12.5", "999", "1000", "123456.789", "1234567.5", "-45000", "99999999.99", "0.05", "10000000"];
const fmt = amounts.flatMap((a) => [0, 2, 3].map((d) => ({ amount: a, decimals: d, expected: formatIndian(a, d) })));
const words = ["0", "1", "21.5", "100", "1001", "99999", "100000", "1234567.89", "99999999.99", "10000000"].map((a) => ({ amount: a, expected: amountInWords(a, "en") }));
writeFileSync("test/fixtures/format_vectors.json", JSON.stringify({ fmt, words }));

const slabCases = [];
for (let i = 0; i < 3000; i++) {
  const slab = pick(["apparel", "footwear", null]);
  const item = { gstRate: pick(GST_RATES), gstSlab: slab, slabPieces: pick([1, 1, 1, 2, 3, 4, 6, 12]) };
  const qty = rnd() < 0.5 ? String(1 + Math.floor(rnd() * 50)) : (0.5 + rnd() * 30).toFixed(pick([1, 2, 3]));
  const edge = [1000, 2500, 1050, 2625, 1120, 2800];
  const rate = rnd() < 0.4 ? String(pick(edge) * item.slabPieces + pick([-1, 0, 1, 0.01, -0.01])) : (1 + rnd() * 6000 * item.slabPieces).toFixed(pick([2, 3]));
  const gross = Number(qty) * Number(rate);
  const discount = rnd() < 0.3 ? (gross * rnd() * 0.4).toFixed(2) : "0";
  const date = pick(["2017-06-30", "2017-07-01", "2022-01-01", "2025-09-21", "2025-09-22", "2026-04-01"]);
  slabCases.push({ item, line: { qty, rate, discount }, date, expected: lineGstRate(item, { qty, rate, discount }, date) });
}
writeFileSync("test/fixtures/slab_vectors.json", JSON.stringify(slabCases));

const states = GST_STATES.map((s) => `  State("${s.code}", ${JSON.stringify(s.name)}, ${s.ut ? "true" : "false"}),`).join("\n");
writeFileSync("lib/core/states.dart", `// Generated by tool/gen_vectors.mjs from packages/domain. Do not edit by hand.\nclass State {\n  final String code;\n  final String name;\n  final bool ut;\n  const State(this.code, this.name, this.ut);\n}\n\nconst List<State> gstStates = [\n${states}\n];\n\nState? findState(String code) {\n  for (final s in gstStates) { if (s.code == code) return s; }\n  return null;\n}\n`);
console.log("cases", cases.length, "fmt", fmt.length, "words", words.length, "states", GST_STATES.length);
