/**
 * Writes docs/api.md from the routes the API actually registers, with the permission each one needs:
 *
 *   npm run docs:api -w @varchasv/api
 *
 * The security test sweeps the same table, so what this document says is what the API enforces.
 */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createDb } from "@varchasv/db";
import { buildApp } from "../src/app.js";
import { LogMailer } from "../src/lib/mailer.js";
import { PUBLIC_ROUTES } from "../src/lib/public-routes.js";

const out = resolve(dirname(fileURLToPath(import.meta.url)), "../../../docs/api.md");
// buildApp only registers routes here; no query runs, so the connection is never opened.
const conn = createDb(process.env.DATABASE_URL ?? "postgres://varchasv_app:varchasv_app_dev@localhost:5433/varchasv", { max: 1 });
const app = await buildApp({ db: conn.db, logger: false, rateLimits: false, mailer: new LogMailer(() => {}) });
const routes = app.routeTable.filter((r) => r.method !== "OPTIONS");
await app.close();
await conn.close();

const AREAS: [RegExp, string][] = [
  [/^\/(health|auth|tenants|invitations|meta|tools)/, "Sign-in, businesses and helpers"],
  [/^\/(companies|branches|roles|members|devices|audit-log|number-series|fiscal-years|financial-years)/, "Company, team and settings"],
  [/^\/(accounts|vouchers|reports\/(trial|profit|balance|ledger|day-book|cash-flow))/, "Accounting"],
  [/^\/(gst|einvoice|eway|returns|import|print-language)/, "GST, returns and import"],
  [/^\/(items|warehouses|uoms|inventory|stock|reports\/stock)/, "Inventory"],
  [/^\/(purchase|goods-receipts|reports\/payables)/, "Purchasing"],
  [/^\/(quotations|sales|delivery-notes|credit-notes|reports\/receivables|outstanding|reminders)/, "Sales"],
  [/^\/(pos)/, "Point of sale"],
  [/^\/(boms|work-centres|production|mrp|job-work)/, "Manufacturing"],
  [/^\/(employees|attendance|leave|holidays|shifts|payroll|payslips|statutory|settlements|loans|tds)/, "HR and payroll"],
  [/^\/(banking)/, "Banking"],
  [/^\/(assets)/, "Fixed assets"],
  [/^\/(expenses|files)/, "Expenses"],
  [/^\/(projects|timesheets)/, "Projects"],
  [/^\/(crm|messages)/, "CRM"],
  [/^\/(analytics|reports|assistant|purchase-bills\/read)/, "Analytics, reports and assistant"],
  [/^\/(sync)/, "Offline app sync"],
  [/^\/(cron)/, "Scheduled jobs"],
];
const area = (url: string) => AREAS.find(([re]) => re.test(url))?.[1] ?? "Other";
const access = (r: (typeof routes)[number]) =>
  PUBLIC_ROUTES.has(`${r.method} ${r.url}`) ? "public" : r.url.startsWith("/cron/") ? "scheduler (`CRON_SECRET`)" : r.permissions.length ? r.permissions.map((p) => `\`${p}\``).join(" or ") : "signed in";

const groups = new Map<string, typeof routes>();
for (const r of [...routes].sort((a, b) => a.url.localeCompare(b.url) || a.method.localeCompare(b.method))) {
  const g = area(r.url);
  groups.set(g, [...(groups.get(g) ?? []), r]);
}
const order = [...AREAS.map(([, name]) => name), "Other"].filter((n) => groups.has(n));

const lines = [
  "# Varchasv ERP API reference",
  "",
  "Generated by `npm run docs:api -w @varchasv/api` from the routes the API registers. Don't edit by hand.",
  "",
  "## Basics",
  "",
  "- **Base URL:** `http://localhost:4100` in development. The web app calls it through `/api` on its own origin.",
  "- **Signing in:** `POST /auth/login` with `{ email, password }` sets the `vsid` session cookie (httpOnly, SameSite=Lax, Secure in production). The offline app sends `client: \"app\"` and gets a `token`, which it sends as `Authorization: Bearer <token>`.",
  "- **Business:** every call works on the signed-in user's current business (`POST /auth/switch` changes it). Row-level security in Postgres keeps each business's data separate.",
  "- **Access:** each route below lists the permission it needs. *signed in* means any member of the business; the handler limits what it returns to the member's permissions (the dashboard, report builder and assistant work this way). *public* routes need no session.",
  "- **Bodies:** JSON. Money and quantities are strings (`\"1250.50\"`), dates are `YYYY-MM-DD`.",
  "- **Errors:** `{ \"error\": \"<code>\" }` with 400 (validation, plus `issues: [{ path, message }]`), 401 (not signed in), 403 (`missing_permission`, `no_tenant`), 404, 409 (conflicts such as `email_taken`) or 429 (rate limit).",
  "- **Rate limits:** 600 requests a minute per session (`RATE_LIMIT_PER_MINUTE`); sign-in 10 per 5 minutes, sign-up 10 an hour, password reset 5 per 15 minutes per IP.",
  "- **Lists:** document lists return the newest 500; pass `from` and `to` to reach older ones.",
  "",
  `## Routes (${routes.length})`,
  "",
];
for (const name of order) {
  const rs = groups.get(name)!;
  lines.push(`### ${name}`, "", "| Method | Path | Access |", "|---|---|---|");
  for (const r of rs) lines.push(`| ${r.method} | \`${r.url}\` | ${access(r)} |`);
  lines.push("");
}
writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out} (${routes.length} routes)`);
