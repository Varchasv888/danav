import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { LOCALES, READY_LOCALES } from "../locales.js";

/**
 * Generates Flutter ARB files from the JSON catalogues, so the offline app and the web app
 * share one set of translations. "auth.errors.email_taken" becomes the ARB key "authErrorsEmailTaken".
 */
type Tree = { [k: string]: string | Tree };
const outDir = fileURLToPath(new URL("../../../apps/varchasv/lib/l10n/", import.meta.url));
mkdirSync(outDir, { recursive: true });

const camel = (parts: string[]) =>
  parts.flatMap((p) => p.split("_")).map((p, i) => (i === 0 ? p : p.charAt(0).toUpperCase() + p.slice(1))).join("");

function flatten(t: Tree, path: string[] = [], out: Record<string, string> = {}) {
  for (const [k, v] of Object.entries(t)) {
    if (typeof v === "string") out[camel([...path, k])] = v;
    else flatten(v, [...path, k], out);
  }
  return out;
}

for (const code of READY_LOCALES) {
  const flat = flatten(JSON.parse(readFileSync(new URL(`../messages/${code}.json`, import.meta.url), "utf8")));
  const arb: Record<string, unknown> = { "@@locale": code };
  for (const [k, v] of Object.entries(flat)) {
    arb[k] = v;
    // Plural selectors are numbers; every other argument (select selectors included) is a string.
    const plural = new Set([...v.matchAll(/\{(\w+)\s*,\s*plural\s*,/g)].map((m) => m[1]!));
    const params = new Set([...v.matchAll(/\{(\w+)\}/g)].map((m) => m[1]!));
    if (code === "en" && params.size) {
      arb[`@${k}`] = { placeholders: Object.fromEntries([...params].map((p) => [p, { type: plural.has(p) ? "num" : "String" }])) };
    }
  }
  writeFileSync(`${outDir}app_${code}.arb`, JSON.stringify(arb, null, 2) + "\n");
  console.log(`wrote app_${code}.arb (${Object.keys(flat).length} strings)`);
}

// The language menu in the app: shipped languages in menu order, with their own names.
const menu = LOCALES.filter((l) => l.ready).map((l) => `  (code: '${l.code}', native: '${l.native}'),`).join("\n");
writeFileSync(
  `${outDir}languages.dart`,
  `// Generated by packages/i18n/scripts/arb.ts from locales.js. Do not edit.\n\nconst appLanguages = <({String code, String native})>[\n${menu}\n];\n`,
);
console.log(`wrote languages.dart (${READY_LOCALES.length} languages)`);
